// ACRYL packages shared on GitHub without npm (acryldev/acryl spec 044, decisions 1-3): a public repository with the topic `acryl-package` and a
// release whose one `.tgz` asset is the package. The catalog lists it from that tarball: its package.json read from inside it, never executed,
// and its sha512 recorded so an install can check it.
import { createHash } from 'node:crypto'
import { gunzipSync } from 'node:zlib'
import { catalogPluginFromManifest } from './acryl-catalog.mjs'

const BLOCK = 512

function field(block, offset, length) {
  const slice = block.subarray(offset, offset + length)
  const end = slice.indexOf(0)
  return Buffer.from(end === -1 ? slice : slice.subarray(0, end)).toString('utf8')
}

/** The package.json inside an npm-style tarball (`package/package.json`, any first directory), or null. */
export function packageJsonFromTarball(gzipped, maxBytes = 64 * 1024 * 1024) {
  const archive = gunzipSync(gzipped, { maxOutputLength: maxBytes })
  let offset = 0
  let longPath
  while (offset + BLOCK <= archive.length) {
    const block = archive.subarray(offset, offset + BLOCK)
    if (block.every(byte => byte === 0)) break
    const size = Number.parseInt(field(block, 124, 12).trim() || '0', 8)
    const type = String.fromCharCode(block[156] ?? 0)
    const content = archive.subarray(offset + BLOCK, offset + BLOCK + size)
    offset += BLOCK + Math.ceil(size / BLOCK) * BLOCK
    if (type === 'x') { longPath = /(?:^|\n)\d+ path=(.*)\n/u.exec(Buffer.from(content).toString('utf8'))?.[1]; continue }
    const prefix = field(block, 345, 155)
    const path = longPath ?? (prefix === '' ? field(block, 0, 100) : `${prefix}/${field(block, 0, 100)}`)
    longPath = undefined
    if ((type === '0' || type === '\0') && path.split('/').slice(1).join('/') === 'package.json') {
      try { return JSON.parse(Buffer.from(content).toString('utf8')) } catch { return null }
    }
  }
  return null
}

export function integrityOf(bytes) {
  return `sha512-${createHash('sha512').update(bytes).digest('base64')}`
}

/** The service contract and slots a package declares (generated by ACRYL when it is shared), if any. */
function contractOf(manifest) {
  const acryl = manifest?.acryl
  if (typeof acryl !== 'object' || acryl === null) return {}
  const lists = value => (typeof value === 'object' && value !== null && !Array.isArray(value) ? value : undefined)
  return {
    ...(lists(acryl.requires) ? { requires: acryl.requires } : {}),
    ...(lists(acryl.provides) ? { provides: acryl.provides } : {}),
    ...(lists(acryl.slots) ? { slots: acryl.slots } : {}),
  }
}

/**
 * A catalog entry for a GitHub release. The install line works in stock DSH and in ACRYL alike: DSH's installer takes the release tarball's
 * https URL; ACRYL also checks its sha512.
 */
export function catalogPluginFromRelease({ manifest, repository, owner, release, asset, integrity }) {
  const base = catalogPluginFromManifest(manifest, { date: release.published_at, publisher: { username: owner } })
  if (base === null) return null
  return {
    ...base,
    repository,
    install: `dsh plugin --profile desktop add ${asset.browser_download_url}`,
    tarball: asset.browser_download_url,
    integrity,
    releaseTag: release.tag_name,
    ...contractOf(manifest),
  }
}

/** Merge npm and GitHub entries: one per repository and per id, npm first (an npm package is the more specific install). */
export function mergeCatalogEntries(npmEntries, githubEntries) {
  const repositories = new Set(npmEntries.map(entry => entry.repository.toLowerCase()))
  const ids = new Set(npmEntries.map(entry => entry.id))
  return [...npmEntries, ...githubEntries.filter(entry => !repositories.has(entry.repository.toLowerCase()) && !ids.has(entry.id))]
}
